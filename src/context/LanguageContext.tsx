export type TranslationKey = keyof typeof translations.en;

interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  getCategoryName: (cat: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

function getInitialLanguage(): LanguageCode {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem('spendwise_lang') as LanguageCode | null;
    if (saved && translations[saved]) return saved;
  } catch {
    // Ignore error
  }
  return 'en';
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(getInitialLanguage);

  const setLanguage = (lang: LanguageCode) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('spendwise_lang', lang);
    } catch {
      // Ignore error
    }
  };

  const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
    const dict = translations[language] || translations.en;
    let text = (dict as Record<string, string>)[key] || (translations.en as Record<string, string>)[key] || key;
    if (params) {
      Object.entries(params).forEach(([paramKey, val]) => {
        text = text.replace(new RegExp(`%${paramKey}%`, 'g'), String(val));
      });
    }
    return text;
  };

  const getCategoryName = (cat: string): string => {
    switch (cat) {
      case 'Food':
      case 'Food & Dining':
        return t('catFood');
      case 'Shopping':
        return t('catShopping');
      case 'Transport':
      case 'Transportation':
        return t('catTransport');
      case 'Bills':
        return t('catBills');
      case 'Entertainment':
        return t('catEntertainment');
      case 'Health':
      case 'Healthcare':
        return t('catHealth');
      case 'Education':
        return t('catEducation');
      case 'Housing':
        return t('catHousing');
      case 'Utilities':
        return t('catUtilities');
      case 'Salary':
        return t('catSalary');
      case 'Freelance':
        return t('catFreelance');
      case 'Investments':
        return t('catInvestments');
      default:
        return t('catOther');
    }
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, getCategoryName }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
